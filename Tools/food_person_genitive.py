def person_accusative(person):
    surname, first, patronymic = person['name'].split()
    # Женские фамилии на согласную и -о не склоняются.
    if patronymic.endswith('вна') and surname[-1] in 'БВГҐДЖЗКЛМНПРСТФХЦЧШЩЬЙО':
        return RANKS[person['rank']], f'{surname} {FIRST_NAMES[first]} {patronymic[:-1]}у'
    if surname in SURNAME_EXCEPTIONS:
        surname = SURNAME_EXCEPTIONS[surname]
    elif surname.endswith('ИЙ'):
        surname = surname[:-2] + 'ОГО'
    elif surname.endswith('А'):
        surname = surname[:-1] + 'У'
    elif surname.endswith('Я'):
        surname = surname[:-1] + 'Ю'
    elif surname.endswith('ІЙ'):
        surname = surname[:-2] + 'ЬОГО'
    elif surname.endswith('О'):
        surname = surname[:-1] + 'А'
    elif surname.endswith(('Ь', 'Й')):
        surname = surname[:-1] + 'Я'
    elif surname[-1] in 'БВГҐДЖЗКЛМНПРСТФХЦЧШЩ':
        surname += 'А'
    else:
        raise ValueError(f'Нужна морфологическая проверка фамилии: {surname}')
    if not patronymic.endswith('ич'):
        raise ValueError(f'Нужна проверка отчества: {patronymic}')
    return RANKS[person['rank']], f'{surname} {FIRST_NAMES[first]} {patronymic}а'