def people(lines):
    result = []
    for line in lines:
        line = line.strip().rstrip('.;')
        line = re.sub(r'^\d+[.)]?\s*', '', line)
        line = line.replace('солат ', 'солдат ').replace('мол. сержант ', 'молодший сержант ').replace('штаб сержант ', 'штаб-сержант ')
        parts = line.split()
        name = ' '.join([parts[-3].upper(), *parts[-2:]])
        result.append({'rank': ' '.join(parts[:-3]).lower(), 'name': name})
    return result

